// دالة الترجمة الأساسية: بتاخد اللغة والمفتاح، ولو المفتاح مش موجود بترجع نفس المفتاح
export function t(lang, key) {
  return translations[lang]?.[key] ?? translations.en[key] ?? key;
}

// دالة ترجمة بتدعم استبدال متغيرات جوه النص، زي {name} أو {days}
// مثال: tf(lang, "basedOnBudget", { budget: 5000, days: 4 })
export function tf(lang, key, vars = {}) {
  let text = t(lang, key);
  Object.entries(vars).forEach(([k, v]) => {
    text = text.replace(new RegExp(`{${k}}`, "g"), v);
  });
  return text;
}

// ترجمة اسم الفئة (زي History, Beach, Adventure...) مع رجوع الاسم الأصلي لو مش موجود
export function tCategory(lang, category) {
  if (!category) return category;
  return t(lang, `cat_${category}`) !== `cat_${category}` ? t(lang, `cat_${category}`) : category;
}
